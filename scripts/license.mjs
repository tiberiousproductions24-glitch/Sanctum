#!/usr/bin/env node
// Sanctum license tool (owner-only). Mints offline-verifiable Ed25519-signed tokens.
// The PRIVATE key lives only in licensing-keys/ (gitignored, chmod 600) and is never bundled.
//   npm run license:keygen                      create the keypair (once) + write src/license/pubkey.ts
//   npm run license:invite -- --name "Alice" [--days 30] [--uses 1] [--plan full|perform|trial] [--device XXXX-XXXX-XXXX-XXXX]
//   npm run license:admin                       mint a non-expiring admin token → licensing-keys/ADMIN-TOKEN.txt
//   npm run license:verify -- <code>            decode + verify a code
//   node scripts/license.mjs mint --type invite --days -1 [--json]   (tests: e.g. an already-expired token)
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const KEYDIR = process.env.SANCTUM_KEYDIR || path.join(ROOT, 'licensing-keys');
const PRIV = path.join(KEYDIR, 'sanctum-license-ed25519.pem');
const PUBTS = path.join(ROOT, 'src', 'license', 'pubkey.ts');
const LOG = path.join(KEYDIR, 'issued.jsonl');
const TYPES = { invite: 1, purchase: 2, admin: 3 };
const PLANS = { full: 1, perform: 2, trial: 3 };
const PREFIX = 'S1-';

const args = process.argv.slice(2);
const cmd = args[0];
const opt = (k, d) => { const i = args.indexOf('--' + k); return i >= 0 ? (args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : true) : d; };
const b64u = (b) => Buffer.from(b).toString('base64url');

function keygen(force = false) {
  fs.mkdirSync(KEYDIR, { recursive: true, mode: 0o700 });
  if (fs.existsSync(PRIV) && !force) { writePub(); return console.log('Keypair already exists in licensing-keys/ (not overwritten). Public key synced to src/license/pubkey.ts.'); }
  const { privateKey } = crypto.generateKeyPairSync('ed25519');
  fs.writeFileSync(PRIV, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 });
  fs.chmodSync(PRIV, 0o600);
  writePub();
  console.log('Created licensing-keys/sanctum-license-ed25519.pem (chmod 600) and src/license/pubkey.ts.');
}
function loadKey() {
  if (!fs.existsSync(PRIV)) { console.error('No private key. Run: npm run license:keygen'); process.exit(1); }
  return crypto.createPrivateKey(fs.readFileSync(PRIV));
}
function rawPub(priv) { return crypto.createPublicKey(priv).export({ type: 'spki', format: 'der' }).subarray(-32); }
function writePub() {
  const pub = Buffer.from(rawPub(loadKey())).toString('hex');
  fs.writeFileSync(PUBTS, `// Generated by scripts/license.mjs — Ed25519 PUBLIC key used to verify Sanctum license tokens.\n// Safe to ship. The matching private key stays in licensing-keys/ (never committed or bundled).\nexport const LICENSE_PUBKEY_HEX = '${pub}';\n`);
}
export const deviceHash = (deviceId) => crypto.createHash('sha256').update(String(deviceId).trim().toUpperCase()).digest().subarray(0, 8);

function mint({ type, plan = 'full', days, name, device }) {
  const priv = loadKey();
  const now = Math.floor(Date.now() / 1000);
  const id = crypto.randomBytes(8);
  const nameB = name ? Buffer.from(String(name)).subarray(0, 32) : null;
  let flags = 0; if (days != null) flags |= 1; if (device) flags |= 2; if (nameB) flags |= 4;
  const parts = [Buffer.from([1, TYPES[type], PLANS[plan] || 1, flags]), id];
  const u32 = (n) => { const b = Buffer.alloc(4); b.writeUInt32BE(Math.max(0, n) >>> 0); return b; };
  parts.push(u32(now));
  let expiry = null;
  if (days != null) { expiry = now + Math.round(Number(days) * 86400); parts.push(u32(expiry)); }
  if (device) parts.push(deviceHash(device));
  if (nameB) parts.push(Buffer.from([nameB.length]), nameB);
  const body = Buffer.concat(parts);
  const sig = crypto.sign(null, body, priv);
  const code = PREFIX + b64u(Buffer.concat([body, sig]));
  return { code, id: id.toString('hex'), type, plan, issued: new Date(now * 1000).toISOString(), expiry: expiry ? new Date(expiry * 1000).toISOString() : null, name: name || null, device: device || null };
}
function verify(code) {
  const raw = Buffer.from(String(code).trim().replace(/^.*[?&]code=/, '').replace(/^S1-/, ''), 'base64url');
  const body = raw.subarray(0, raw.length - 64), sig = raw.subarray(raw.length - 64);
  const ok = crypto.verify(null, body, crypto.createPublicKey(loadKey()), sig);
  return { signatureValid: ok, type: Object.keys(TYPES)[body[1] - 1], plan: Object.keys(PLANS)[body[2] - 1], id: body.subarray(4, 12).toString('hex') };
}
const log = (rec) => fs.appendFileSync(LOG, JSON.stringify({ ...rec, code: undefined, loggedAt: new Date().toISOString() }) + '\n', { mode: 0o600 });
const links = (code) => ({ deep: `sanctum://activate?code=${code}`, https: `https://sanctum.app/activate?code=${code}` });

if (cmd === 'keygen') keygen(opt('force') === true);
else if (cmd === 'invite') {
  const name = opt('name'); if (!name || name === true) { console.error('Usage: npm run license:invite -- --name "Name" [--days N] [--uses 1] [--plan full] [--device ID]'); process.exit(1); }
  const days = opt('days'); const uses = Number(opt('uses', 1));
  const r = mint({ type: 'invite', plan: opt('plan', 'full'), days: days === undefined ? undefined : Number(days), name, device: opt('device') === true ? undefined : opt('device') });
  log({ ...r, uses });
  const l = links(r.code);
  console.log(`Invite for ${name} (id ${r.id}, plan ${r.plan}, ${r.expiry ? 'expires ' + r.expiry : 'no expiry'}${r.device ? ', bound to device ' + r.device : ''}).`);
  console.log(`\nCode (paste on the lock screen → "I have a code"):\n${r.code}\n\nTap-to-open link (Android app installed):\n${l.deep}\n\nWeb form (placeholder domain, for later):\n${l.https}\n`);
  if (uses !== 1 || !r.device) console.log('Note: offline codes can\'t enforce single use across devices. For a hard one-device invite, ask for the Device ID shown on their lock screen and pass --device.');
} else if (cmd === 'admin') {
  const r = mint({ type: 'admin', plan: 'full', name: opt('name', 'Lawrence Davis Sr') });
  log(r);
  const f = path.join(KEYDIR, 'ADMIN-TOKEN.txt');
  fs.writeFileSync(f, r.code + '\n', { mode: 0o600 }); fs.chmodSync(f, 0o600);
  console.log(`Admin token (id ${r.id}, non-expiring) written to licensing-keys/ADMIN-TOKEN.txt (chmod 600). Not printed.`);
} else if (cmd === 'mint') {
  const r = mint({ type: opt('type', 'invite'), plan: opt('plan', 'full'), days: opt('days') === undefined ? undefined : Number(opt('days')), name: opt('name') === true ? undefined : opt('name'), device: opt('device') === true ? undefined : opt('device') });
  if (!opt('nolog')) log({ ...r, test: true });
  console.log(opt('json') ? JSON.stringify(r) : r.code);
} else if (cmd === 'verify') console.log(verify(args[1]));
else { console.error('Commands: keygen | invite | admin | verify | mint'); process.exit(1); }
